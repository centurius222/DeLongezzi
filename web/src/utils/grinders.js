export const GRINDER_BRANDS = Object.keys(GRINDERS).sort((a, b) =>
  a === 'Other' ? 1 : b === 'Other' ? -1 : a.localeCompare(b, undefined, { sensitivity: 'base' }),
);

// "Brand|Model" <-> { brand, model }; the machine stores the string (Settings lastGrinder).
export const splitGrinder = s => {
  const [brand = '', model = ''] = String(s || '').split('|');
  return GRINDERS[brand]
    ? { brand, model: GRINDERS[brand].includes(model) ? model : '' }
    : { brand: '', model: '' };
};
export const joinGrinder = (brand, model) => (brand ? `${brand}|${model || ''}` : '');
export const grinderName = s => {
  const { brand, model } = splitGrinder(s);
  if (!brand) return '';
  return brand === 'Other' ? 'Other grinder' : `${brand} ${model}`.trim();
};
