// Flanking stat beside the start button. Deliberately NOT a circle: the round
// filled button in the middle stays the only thing that looks pressable.
function FlankStat({ value, unit, size, dimmed = false, onTap }) {
  // The tappable variant is a button around the whole block, and the unit line
  // carries the hint. Nothing else in this row is pressable — the round button
  // in the middle is deliberately the only thing that looks it — so a big
  // number that silently does something would never be found. Underlining the
  // figure was the alternative and collides with the label beneath it.
  const Wrapper = onTap ? 'button' : 'div';
  const wrapperProps = onTap
    ? { type: 'button', onClick: onTap, 'aria-label': 'Zero the scale' }
    : {};
  return (
    <Wrapper
      {...wrapperProps}
      className={`flex-1 text-center ${dimmed ? 'text-base-content/30' : 'text-base-content'}`}
    >
      {/* An invisible copy of the unit line, above. The row is items-center, so
          without it the two-line block gets centred against the circle and the
          NUMBER ends up sitting half a unit-label higher than the timer inside
          it — about 12px, which reads as a wonky row. Balancing the block puts
          the number itself on the centre line. A hand-tuned margin would do the
          same until someone changes the label's size. */}
      <div aria-hidden='true' className='invisible mb-1 text-sm font-medium'>
        {unit}
      </div>
      <div className={`${size} leading-none font-bold tabular-nums`}>{value}</div>
      <div className='text-base-content/50 mt-1 text-sm font-medium'>{unit}</div>
    </Wrapper>
  );
}

FlankStat.propTypes = {
  value: PropTypes.oneOfType([PropTypes.string, PropTypes.number]).isRequired,
  unit: PropTypes.string.isRequired,
  size: PropTypes.string.isRequired,
  dimmed: PropTypes.bool,
  onTap: PropTypes.func,
};

/**
 * The start / stop button (see the notes at its use in ManualCard): readiness
 * glow, heat ring or comet, the cup when idle and the shot time while running
 * and after. Shared with the full-screen MANUAL page (ManualScreen.jsx), which
 * passes `size` (a CSS length) for a bigger button; the cup scales with it and
 * `timeClass` sizes the time. Without `size` it is exactly the 144px button.
 */
// Brew button bezel over custom art: the card colour nudged toward the text
// colour (brighter on dark themes, darker on light ones).
const BEZEL = 'color-mix(in oklab, var(--color-base-100) 78%, var(--color-base-content))';

export function CupButton({
  running,
  elapsed,
  glow,
  heatProgress,
  onClick,
  size,
  timeClass = 'text-6xl',
  plain = false,
  numStyle = null,
}) {
  // The library's video for now (the theme's pick, or Settings' one / shuffled one); plain:
  // always the original cup (the library's "Original cup" tile).
  const liveId = plain ? '' : brewVideoId.value;
  // While a shot runs the button keeps its video (user 2026-10-09): a theme changed mid-shot
  // swapped it for the plain button while the new video downloaded, a big file on top of the
  // shot, and the tablet fell out of step. The new one takes over when the shot ends. The first
  // moments of a shot still take the shuffle's next video (onShotStart), and a page opened
  // mid-shot still gets its first video.
  const [videoId, setVideoId] = useState(liveId);
  const startedAt = useRef(0);
  if (running && !startedAt.current) startedAt.current = Date.now();
  if (!running) startedAt.current = 0;
  useEffect(() => {
    if (!running || videoId === '' || Date.now() - startedAt.current < 1500) setVideoId(liveId);
  }, [liveId, running]);
  const [art, setArt] = useState(() => getBrewArt(videoId));
  const [animUrl, setAnimUrl] = useState(null);
  useEffect(() => {
    loadBrewState();
  }, []);
  useEffect(() => {
    let alive = true;
    holdBrewAnim(videoId);
    setArt(getBrewArt(videoId));
    loadBrewStill(videoId).then(a => alive && setArt(a));
    loadBrewAnim(videoId).then(a => alive && a && setArt(a));
    return () => {
      alive = false;
      releaseBrewAnim(videoId); // a theme left: its video stops downloading (2026-10-18)
    };
  }, [videoId]);
  // Shuffling: a new shot may bring the next video (utils/brewArt.js onShotStart).
  const wasRunning = useRef(running);
  useEffect(() => {
    if (running && !wasRunning.current) onShotStart();
    wasRunning.current = running;
  }, [running]);
  // A fresh object URL per shot restarts the animation at its first frame
  // without downloading it again (GIF/WebP; a video restarts by seeking).
  useEffect(() => {
    if (!art || !art.anim || art.video || !running) return undefined;
    const url = URL.createObjectURL(art.anim);
    setAnimUrl(url);
    return () => {
      URL.revokeObjectURL(url);
      setAnimUrl(null);
    };
  }, [art, running]);
  // Video art: restart from the first frame when a shot starts, freeze on the
  // current frame when it stops; the element stays until the shot is cleared.
  const videoRef = useRef(null);
  useEffect(() => {
    const v = videoRef.current;
    if (!art?.video || !v) return;
    if (running) {
      v.currentTime = 0;
      v.play().catch(() => {});
    } else {
      v.pause();
    }
  }, [art, running]);

  return (
    <div data-slot='brew' className='relative flex shrink-0'>
      <button
        type='button'
        className={`btn btn-circle relative ${size ? '' : 'h-36 w-36'} shrink-0 overflow-hidden border-0 !bg-transparent text-white before:absolute before:inset-0 before:z-0 before:content-[''] ${
          running ? 'before:animate-[gm-hue-roll_8s_linear_infinite]' : ''
        }`}
        style={{
          // Inline because the colours are computed from live
          // temperature; Tailwind cannot express a dynamic gradient.
          '--gm-c1': glow.c1,
          '--gm-c2': glow.c2,
          ...(size ? { width: size, height: size, '--gm-cup': `calc(${size} * 0.78)` } : {}),
          // Custom art: two rings just OUTSIDE the circle (shadows with spread,
          // so neither the button nor the art shrinks), user 2026-09-24: 3 px of
          // the theme accent over 12 px of the card colour nudged toward the text
          // colour (a touch brighter on dark themes, darker on light ones), so
          // every theme gets a matching bezel: 3 px accent + 9 px bezel.
          ...(art
            ? {
                boxShadow: `0 0 0 3px color-mix(in oklab, var(--color-primary) 55%, ${BEZEL}), 0 0 0 12px ${BEZEL}`,
              }
            : {}),
        }}
        onClick={onClick}
        aria-label={running ? 'Stop' : 'Start'}
        title={running ? 'Stop' : 'Start'}
      >
        <span
          className='absolute inset-0 z-0'
          style={{
            background: `radial-gradient(circle at 50% 42%, ${glow.c1}, ${glow.c2})`,
          }}
        />
        {/* Custom art fills the whole circle (the round button crops it) and
            replaces the heat ring: no comet around it (user 2026-09-24). */}
        {art &&
          (art.video && (running || elapsed > 0) ? (
            <video
              ref={videoRef}
              src={art.videoUrl}
              muted
              playsInline
              loop={!brewVideoOnce.value}
              className='absolute inset-0 h-full w-full object-cover'
            />
          ) : (
            <img
              src={!art.video && running && animUrl ? animUrl : art.still}
              alt=''
              className='absolute inset-0 h-full w-full object-cover'
            />
          ))}
        {!art && <ProgressRing progress={heatProgress} spinning={running} />}
        <span className='relative z-10 flex items-center justify-center'>
          {art ? (
            (running || elapsed > 0) && (
              <span
                className={`${timeClass} leading-none font-extrabold tracking-tight tabular-nums`}
                style={
                  numStyle || {
                    color: art.numColor,
                    opacity: art.numOpacity,
                    transform: `scale(${art.numSize})`,
                  }
                }
              >
                {fmtElapsed(elapsed)}
              </span>
            )
          ) : running || elapsed > 0 ? (
            <span
              className={`${timeClass} leading-none font-extrabold tracking-tight tabular-nums`}
              style={numStyle || brewNumStyle.value}
            >
              {fmtElapsed(elapsed)}
            </span>
          ) : (
            /* Sized with explicit dimensions rather than font-size, so
               the artwork nearly fills the button (112 of 144px, 78 %). */
            <CupIcon className={size ? 'h-[var(--gm-cup)] w-[var(--gm-cup)]' : 'h-28 w-28'} />
          )}
        </span>
      </button>
      <Decor pieces={['rim', 'topper']} />
    </div>
  );
}

