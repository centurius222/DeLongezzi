/**
 * Everything the manual controls know and do, shared by the panel below and
 * the full-screen MANUAL page (ManualScreen.jsx), so both behave exactly alike.
 * Moved out of ManualCard unchanged (2026-09-23).
 *
 * The machine owns all of this state: the toggle switches mode, the button
 * starts/stops a ManualProcess, and pressure, temperature and the weight target
 * are firmware values echoed back over the status stream. The only local state
 * is the in-flight pressure value while dragging, and the remembered weight
 * target so disarming does not lose it. See MANUAL_MODE_PLAN.md.
 */
export function useManualControls({
  mode = 0,
  isActive = false,
  activate,
  deactivate,
  changeMode,
  currentWeight = 0,
  currentPuckFlow = 0,
  bluetoothConnected = false,
  manualPressure = 0,
  manualWeight = 0,
  setManualPressure,
  setManualWeight,
  tare,
  targetTemperature = 0,
  currentTemperature = 0,
  raiseTemp,
  lowerTemp,
  processInfo,
}) {
  // Every control below is optimistic: it moves now, and reconciles when the
  // status stream confirms. See useOptimistic above for why.
  const [shownMode, setShownMode] = useOptimistic(mode);
  const [shownActive, setShownActive] = useOptimistic(isActive);
  const [shownPressure, setShownPressure] = useOptimistic(manualPressure, 0.05);
  const [shownTemp, setShownTemp] = useOptimistic(Math.round(targetTemperature));
  const [shownWeightTarget, setShownWeightTarget] = useOptimistic(manualWeight, 0.01);

  const on = shownMode === MODE_MANUAL;
  const running = shownActive;

  // Weight target of 0 means "off" on the firmware side. The last non-zero
  // value is kept locally so arming again restores it rather than starting over.
  const [lastWeight, setLastWeight] = useState(() =>
    readStored(WEIGHT_KEY, v => clampWeight(Number.parseFloat(v)), WEIGHT_FALLBACK),
  );
  useEffect(() => {
    if (shownWeightTarget > 0 && shownWeightTarget !== lastWeight) {
      setLastWeight(shownWeightTarget);
      writeStored(WEIGHT_KEY, shownWeightTarget);
    }
  }, [shownWeightTarget, lastWeight]);

  const weightArmed = shownWeightTarget > 0;
  const weightShown = weightArmed ? shownWeightTarget : lastWeight;

  // Elapsed comes from the firmware (process.e), so it reflects the real shot —
  // including a stop the browser did not initiate, like the weight target
  // firing. It already freezes on completion.
  const elapsed = processInfo?.e ?? 0;

  // Two jobs behind one tap: zero the scale, and clear the finished shot.
  // Enabled when EITHER is available. Requiring a connected scale — which is
  // what this did — stopped making sense the moment the tap also started
  // clearing the shot, because resetting the panel back to the cup is just as
  // useful with no scale at all, and gating it meant there was nothing to press.
  // Idle-only either way: a soak is the pressure slider at 0, which still reads
  // as running, so a shot in progress cannot be cleared out from under you.
  const hasFinishedShot = !running && elapsed > 0;
  const canTare = Boolean(tare) && !running && (bluetoothConnected || hasFinishedShot);

  // Background hue answers "is it ready?". The ring shows the boiler climbing
  // to temperature before a shot, then chases around while one is pulling.
  // A target at or below ambient means there is no target at all — standby
  // reports 0. Guard explicitly: an earlier Math.max(1, target - AMBIENT)
  // avoided the divide-by-zero but turned "no target" into a division by 1, so
  // a warm boiler read as 100% ready and the glow sat green in standby.
  const hasTarget = shownTemp > AMBIENT_C;
  const heatProgress = hasTarget
    ? clamp01((currentTemperature - AMBIENT_C) / (shownTemp - AMBIENT_C))
    : 0;
  // Must be called with the PROGRESS FRACTION, not raw temperatures. It took a
  // (current, target) pair before the switch to interpolated stops; leaving the
  // old call in place fed it 57 as a 0-1 fraction, which clamped to 1.0 and
  // pinned the glow to the "ready" green for any boiler above 1 degree.
  const glow = readinessColor(heatProgress);

  const changePressure = next => {
    const value = clampPressure(next);
    setShownPressure(value);
    setManualPressure?.(value);
  };

  const changeTemp = delta => {
    setShownTemp(shownTemp + delta);
    // The firmware API is a step, not an absolute value, so one message per
    // step is required — it cannot be coalesced into a final value.
    (delta > 0 ? raiseTemp : lowerTemp)?.();
  };

  const changeWeight = delta => {
    const next = clampWeight(weightShown + delta);
    setLastWeight(next);
    writeStored(WEIGHT_KEY, next);
    // Stepping ARMS. It used to only update the remembered number while
    // disarmed and send nothing, so dialling in 30 and pressing go ran the shot
    // to the five-minute backstop with the firmware's target still at 0 — and
    // the panel looked the same either way, only dimmer. Reaching for +/- is an
    // unambiguous statement that you want to stop there; tapping the number is
    // still how you turn it off.
    setShownWeightTarget(next);
    setManualWeight?.(next);
  };

  const toggleWeightArmed = () => {
    const next = weightArmed ? 0 : lastWeight;
    setShownWeightTarget(next);
    setManualWeight?.(next);
  };

  // Off returns to STANDBY, not brew: this panel only exists in standby and
  // manual, so dropping into brew would hide the very toggle you would use to
  // come back. Standby is also where you switched it on from.
  const toggleManual = () => {
    const next = on ? MODE_STANDBY : MODE_MANUAL;
    setShownMode(next);
    changeMode?.(next);
    // A mode change stops any process; do not leave the button showing "running".
    setShownActive(false);
  };

  const togglePump = () => {
    setShownActive(!running);
    (running ? deactivate : activate)?.();
  };

  return {
    on,
    running,
    elapsed,
    hasFinishedShot,
    canTare,
    heatProgress,
    glow,
    shownTemp,
    shownPressure,
    weightArmed,
    weightShown,
    changePressure,
    changeTemp,
    changeWeight,
    toggleWeightArmed,
    toggleManual,
    togglePump,
    currentWeight,
    currentPuckFlow,
    bluetoothConnected,
    tare,
  };
}

/** Manual mode panel (the sidebar card); its logic is useManualControls above. */
export function ManualCard(props) {
  const { inCard = false } = props;
  const {
    on,
    running,
    elapsed,
    hasFinishedShot,
    canTare,
    heatProgress,
    glow,
    shownTemp,
    shownPressure,
    weightArmed,
    weightShown,
    changePressure,
    changeTemp,
    changeWeight,
    toggleWeightArmed,
    toggleManual,
    togglePump,
    currentWeight,
    currentPuckFlow,
    bluetoothConnected,
    tare,
  } = useManualControls(props);

  return (
    <div
      className={
        inCard ? 'flex flex-col gap-4' : 'card bg-base-100 flex flex-col gap-4 rounded-xl p-4'
      }
    >
      <div className='flex items-center justify-between'>
        <div className='text-base-content text-xl font-bold tracking-wide'>Manual</div>
        <input
          type='checkbox'
          className='toggle toggle-primary toggle-lg'
          checked={on}
          onChange={toggleManual}
          aria-label='Manual mode'
        />
      </div>

      {on && (
        <>
          {/* Flow left, button centre, weight right. Every readout in this
              MEASURED values are text-6xl — flow, time and weight. TARGETS
              (temp, stop-at-weight, pressure) are text-4xl and dimmed, so the
              live numbers carry the panel and the setpoints recede.
              The timer is text-6xl too now, which is why the button had to grow
              to 144px — "0:24" at 60px is ~130px wide and needs the diameter to
              clear it. That makes this row the widest thing in the panel, so
              check narrow screens before growing anything here further.
              The button doubles as the shot timer to save a row: play icon
              when idle, live time while running, frozen final time after a
              stop. */}
          <div className='flex items-center justify-between gap-2'>
            {/* Live flow while pulling, shot average once it has finished — the
                firmware switches what it sends, so the label has to switch with
                it. An unlabelled change of meaning is the same trap the stop-at
                weight had: a number that looks identical but is not. */}
            <FlankStat
              value={currentPuckFlow.toFixed(1)}
              unit={!running && elapsed > 0 ? 'g/s avg' : 'g/s'}
              size='text-6xl'
            />
            {/* The button reports state, not just decoration:
                  BACKGROUND hue = readiness (blue cold, amber heating, green
                    ready). A RADIAL glow rather than the old 135deg linear one,
                    which read as a diagonal streak across the cup.
                  RING on the edge = progress. Boiler climb before a shot;
                    weight progress during one, hidden if no target is armed.
                  CENTRE = cup idle, timer running.
                Ring and number never collide: edge versus middle.

                Stacking: the glow is a ::before at z-0 with the button's own
                background forced transparent, and the content lifted to z-10.
                It must NOT be -z-10 — a negative index puts it behind the
                button's background box and it only shows while :active
                repaints. The running hue-roll (gm-hue-roll in style.css) still
                animates, so motion continues to mean "this is pulling". */}
            <CupButton
              running={running}
              elapsed={elapsed}
              glow={glow}
              heatProgress={heatProgress}
              onClick={togglePump}
            />
            {/* Dimmed rather than hidden when the scale is away, so the layout
                never shifts and a disconnected scale is obvious.

                Tap to zero the scale — but only while idle. The weight target
                and the shot average are both measured from this reading, so
                taring mid-pull pulls the reference out from under them and the
                shot runs long. The firmware refuses it during a shot too; this
                only hides the affordance. */}
            <FlankStat
              value={bluetoothConnected ? currentWeight.toFixed(1) : '--'}
              unit={canTare ? (hasFinishedShot ? 'tap to reset' : 'tap to tare') : 'g'}
              size='text-6xl'
              dimmed={!bluetoothConnected}
              onTap={canTare ? tare : undefined}
            />
          </div>

          <BigStepper
            label='Temperature'
            value={shownTemp}
            unit='°C'
            onDecrease={() => changeTemp(-1)}
            onIncrease={() => changeTemp(1)}
          />

          {/* Stop-at-weight. Sits with the other TARGETS rather than beside the
              live weight figure — same category as temp and pressure, same
              dimmed treatment. Tapping the number arms/disarms it; disarmed
              means the shot runs until you press stop, and the value is kept
              either way so your usual target survives. */}
          <BigStepper
            label={weightArmed ? 'Stop at' : 'Stop at — off'}
            value={weightShown}
            unit='g'
            onDecrease={() => changeWeight(-1)}
            onIncrease={() => changeWeight(1)}
            onValueClick={toggleWeightArmed}
            muted={!weightArmed}
          />
          {/* Pressure sits LAST on purpose: it is the control you actively
              ride during a shot, and the bottom of the panel is the comfortable
              thumb zone. Temperature is set once before the shot, so it goes
              above where it is harder to reach.
              Slider and value share one row: the value sits on the right so it
              lines up with the weight figure above it. No "Pressure" label —
              the "bar" unit already identifies it, and the label was costing a
              row. shrink-0 + tabular-nums keeps the number from resizing the
              slider as it counts. */}
          <PressureRow value={shownPressure} onChange={changePressure} />
        </>
      )}
    </div>
  );
}

