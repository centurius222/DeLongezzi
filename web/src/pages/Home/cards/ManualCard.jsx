// Readiness colour, interpolated rather than switched between fixed states.
//
// An earlier version used three discrete colours with a CSS transition, which
// jumped: CSS cannot transition background-image, so a gradient swap is
// instant however long the transition is declared. WaterLevelCard already
// solves this by mixing RGB in JS, so the same approach is used here — the
// status stream ticks twice a second and each tick nudges the colour a little,
// which reads as a smooth roll.
//
// Stops are positioned on heat progress: 0 = ambient, 1 = at target.
const READY_STOPS = [
  [0.0, [56, 189, 248], [79, 70, 229]], // cold      sky      -> indigo
  [0.55, [96, 165, 250], [124, 58, 237]], // warming   blue     -> violet
  [0.85, [251, 191, 36], [217, 119, 6]], // close     amber    -> dark amber
  [1.0, [74, 222, 128], [21, 128, 61]], // ready     green    -> dark green
];

const mix = (a, b, t) => a.map((v, i) => Math.round(v + (b[i] - v) * t));
const rgb = c => `rgb(${c[0]} ${c[1]} ${c[2]})`;

function readinessColor(progress) {
  const p = Number.isFinite(progress) ? Math.min(1, Math.max(0, progress)) : 0;
  let hi = READY_STOPS.findIndex(st => p <= st[0]);
  if (hi <= 0) hi = 1;
  const [p0, a0, b0] = READY_STOPS[hi - 1];
  const [p1, a1, b1] = READY_STOPS[hi];
  const t = p1 === p0 ? 0 : (p - p0) / (p1 - p0);
  return { c1: rgb(mix(a0, a1, t)), c2: rgb(mix(b0, b1, t)) };
}

const clamp01 = v => (Number.isFinite(v) ? Math.min(1, Math.max(0, v)) : 0);

