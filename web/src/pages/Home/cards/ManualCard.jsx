const clamp = (n, lo, hi, fallback) =>
  Number.isFinite(n) ? Math.min(hi, Math.max(lo, n)) : fallback;

const readStored = (key, parse, fallback) => {
  try {
    const stored = globalThis.localStorage?.getItem(key);
    return stored === null || stored === undefined ? fallback : parse(stored);
  } catch {
    return fallback;
  }
};

const writeStored = (key, value) => {
  try {
    globalThis.localStorage?.setItem(key, String(value));
  } catch {
    /* private mode / storage disabled — the value just won't be remembered */
  }
};

const clampPressure = n => clamp(n, PRESSURE_MIN, PRESSURE_MAX, PRESSURE_FALLBACK);
const clampWeight = n => clamp(n, WEIGHT_MIN, WEIGHT_MAX, WEIGHT_FALLBACK);

