function ProgressRing({ progress, spinning = false }) {
  // Two modes on one overlay:
  //   spinning — the comet, meaning "pulling now". Progress toward a weight
  //              target is deliberately not shown: with no scale there is
  //              nothing to fill toward, so it would sit frozen.
  //   progress — a plain stroked fill for the boiler climb before the shot.
  return (
    <svg
      viewBox='0 0 100 100'
      data-part='heat-ring'
      className={`pointer-events-none absolute inset-0 h-full w-full ${
        spinning ? 'animate-[spin_1.15s_linear_infinite]' : '-rotate-90'
      }`}
      aria-hidden='true'
    >
      {spinning ? (
        <path d={COMET_PATH} fill='rgba(255,255,255,0.92)' />
      ) : (
        <circle
          cx='50'
          cy='50'
          r={RING_R}
          fill='none'
          stroke='rgba(255,255,255,0.85)'
          strokeWidth={RING_STROKE}
          strokeLinecap='round'
          strokeDasharray={RING_C}
          strokeDashoffset={RING_C * (1 - clamp01(progress))}
          style={{ transition: 'stroke-dashoffset 400ms ease-out' }}
        />
      )}
    </svg>
  );
}

ProgressRing.propTypes = { progress: PropTypes.number, spinning: PropTypes.bool };

// Press-and-hold repeat. 1 g / 1 °C steps are the right granularity for a
// tweak but a terrible way to travel 18 g, so holding accelerates: one step on
// press, then a repeat every 120ms after a 400ms hold. Pointer events (not
// mouse/touch) so it behaves the same under a finger and a cursor.
function useHoldRepeat(onStep) {
  const timers = useRef({ delay: null, repeat: null });

  const stop = () => {
    clearTimeout(timers.current.delay);
    clearInterval(timers.current.repeat);
    timers.current = { delay: null, repeat: null };
  };

  const start = () => {
    onStep();
    stop();
    timers.current.delay = setTimeout(() => {
      timers.current.repeat = setInterval(onStep, 120);
    }, 400);
  };

  useEffect(() => stop, []);

  return {
    onPointerDown: start,
    onPointerUp: stop,
    onPointerLeave: stop,
    onPointerCancel: stop,
  };
}

// Temp and pressure are TARGETS you set, so they sit at /50 opacity. Time,
// weight and flow are MEASURED values and keep full contrast — the hierarchy
// is "what the machine is doing" over "what I asked it for".
//
// Deliberately not reusing Adjuster.jsx: that component is sized for the grind
// target and is shared with ActionCard. Manual needs noticeably larger hit
// targets, so it gets its own stepper rather than growing everyone else's.
// Show a change the instant it is made, then hand the value back to the machine
// once it confirms. Without this every control sits dead for up to one status
// period (~500ms measured) before it visibly moves, which reads as the button
// not working — and repeated taps trail your finger by a growing margin.
//
// The timeout matters: if the firmware clamps or rejects a value it will never
// echo back what we sent, and without it the panel would show a stale
// optimistic value forever.
const SETTLE_TIMEOUT_MS = 2500;

function useOptimistic(remote, tolerance = 0) {
  const [pending, setPending] = useState(null);

  useEffect(() => {
    if (pending === null) return undefined;
    const settled =
      typeof pending === 'number' && typeof remote === 'number'
        ? Math.abs(pending - remote) <= tolerance
        : pending === remote;
    if (settled) {
      setPending(null);
      return undefined;
    }
    const id = setTimeout(() => setPending(null), SETTLE_TIMEOUT_MS);
    return () => clearTimeout(id);
  }, [pending, remote, tolerance]);

  return [pending === null ? remote : pending, setPending];
}

export function BigStepper({
  label,
  value,
  unit,
  onDecrease,
  onIncrease,
  onValueClick,
  muted = false,
}) {
  const btn =
    'btn btn-circle btn-lg btn-ghost border-base-content/15 flex h-12 w-12 items-center justify-center border';
  const dec = useHoldRepeat(onDecrease);
  const inc = useHoldRepeat(onIncrease);

  const valueEl = (
    <>
      {value}
      <span className='text-base-content/40 ml-1 text-lg font-medium'>{unit}</span>
    </>
  );

  return (
    <div data-part='stepper' className='flex flex-col gap-1'>
      <div data-part='caption' className='text-base-content/60 text-sm font-medium tracking-wide'>
        {label}
      </div>
      <div className='flex items-center justify-between'>
        <button type='button' {...dec} className={btn} aria-label={`Decrease ${label}`}>
          <FontAwesomeIcon icon={faMinus} className='text-xl' />
        </button>
        {onValueClick ? (
          // Tapping the number arms/disarms — one tap instead of stepping all
          // the way down to zero, and it keeps the value while disarmed.
          <button
            type='button'
            onClick={onValueClick}
            data-part='stepper-toggle'
            className='flex flex-col items-center'
            aria-label={`${label}: tap to turn ${muted ? 'on' : 'off'}`}
            title={`Tap to turn ${muted ? 'on' : 'off'}`}
          >
            <span
              data-part='stepper-value'
              className={`text-4xl font-bold tabular-nums ${
                // Struck through when off. A quarter-opacity number next to a
                // half-opacity one is not a difference you notice mid-shot, and
                // reading a disarmed target as armed costs you a flooded cup.
                muted ? 'text-base-content/25 line-through decoration-2' : 'text-base-content/60'
              }`}
            >
              {valueEl}
            </span>
            {/* Says out loud that the number is a switch; styled like the Tare pill (user 2026-09-24). */}
            <span
              data-part='stepper-pill'
              className='bg-primary text-primary-content mt-0.5 rounded-full px-1.5 text-[11px] leading-tight font-medium tracking-wide'
            >
              tap on/off
            </span>
          </button>
        ) : (
          <div
            data-part='stepper-value'
            className='text-base-content/50 text-4xl font-bold tabular-nums'
          >
            {valueEl}
          </div>
        )}
        <button type='button' {...inc} className={btn} aria-label={`Increase ${label}`}>
          <FontAwesomeIcon icon={faPlus} className='text-xl' />
        </button>
      </div>
    </div>
  );
}

